#!/usr/bin/env node
/**
 * integration-assets-manifest.js — content-addressed URLs for the chart-platform
 * study sources that visitors download or copy directly.
 *
 * Same problem, same fix, same cache as scripts/ninjatrader-manifest.js: these
 * live at fixed URLs under frontend/public/, zerogex.io is proxied through
 * Cloudflare with `cache-control: public, max-age=14400`, and `make deploy`
 * never purges it. So for up to four hours after shipping a fixed study, an
 * edge PoP can still hand someone the previous build — and nothing on either
 * end says so. Hashing the bytes into the filename means a new build is a new
 * URL, which no cache anywhere can answer for with something stale.
 *
 * It matters more here than for a normal static asset because these files ARE
 * the product: someone pastes the thinkScript into the Study Editor or builds
 * the .cpp into a DLL, then trades off the result. "Are you sure you have the
 * new one?" is an expensive question to have to ask them.
 *
 * WHY THIS IS A SEPARATE SCRIPT from ninjatrader-manifest.js rather than a
 * generalization of it: that one carries a whole second job — verifying and
 * conditionally publishing an export archive built on someone else's machine,
 * with a null state the pages branch on. These two assets are plain files with
 * no packaging step and no absent state, so folding them in would have meant
 * teaching that script to skip most of itself for most of its inputs. The
 * shared part is nine lines of sha256.
 *
 * Writes:
 *   frontend/core/integrationAssets.ts        (committed — derived from the
 *                                              tracked sources, so a plain
 *                                              `npm run build` needs no
 *                                              pre-step)
 *   frontend/public/<platform>/*.<hash>.<ext> (gitignored)
 *
 * The unhashed paths keep being published alongside, so links already in the
 * wild — the docs, anything someone bookmarked — keep resolving.
 *
 * Dependency-free on purpose: this runs on the deploy box, the same constraint
 * the sibling manifest scripts work under.
 *
 * Usage: node scripts/integration-assets-manifest.js [--check]
 *
 *   --check  write nothing; exit non-zero if the committed manifest is out of
 *            date with respect to the tracked sources.
 */

'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const checkOnly = process.argv.includes('--check');

/**
 * One tracked source per entry.
 *
 * `constant` is the exported name; `dir` is both the public/ subdirectory and
 * the first URL segment. Adding a platform is one entry here plus its landing
 * page — see frontend/core/integrations.ts.
 */
const ASSETS = [
  {
    constant: 'THINKORSWIM_STUDY',
    dir: 'thinkorswim',
    file: 'zerogex-daily-gamma-levels.thinkscript',
    // thinkorswim exports studies as `.ts`, and we deliberately do NOT use
    // that extension: frontend/tsconfig.json includes `**/*.ts` with only
    // node_modules excluded, so a thinkScript file under public/ would be
    // handed to the TypeScript compiler and fail the build.
    description: 'thinkScript study source (manual-entry)',
  },
  {
    constant: 'SIERRACHART_STUDY',
    dir: 'sierrachart',
    file: 'ZeroGexGammaLevels.cpp',
    description: 'Sierra Chart ACSIL study source (auto-updating)',
  },
];

/** First 8 hex of the file's sha256 — same digest the sibling scripts use. */
function hashOf(file) {
  return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex').slice(0, 8);
}

/** `foo.bar.cpp` → `{ stem: 'foo.bar', ext: 'cpp' }` */
function splitExtension(name) {
  const lastDot = name.lastIndexOf('.');
  if (lastDot <= 0) throw new Error(`${name} has no extension to hash into`);
  return { stem: name.slice(0, lastDot), ext: name.slice(lastDot + 1) };
}

const resolved = ASSETS.map((asset) => {
  const source = path.join(ROOT, 'frontend/public', asset.dir, asset.file);
  if (!fs.existsSync(source)) {
    console.error(`  ✗ ${path.relative(ROOT, source)} is missing — it is the source of record`);
    process.exit(1);
  }
  const hash = hashOf(source);
  const { stem, ext } = splitExtension(asset.file);
  return {
    ...asset,
    source,
    hash,
    hashedName: `${stem}.${hash}.${ext}`,
    urlPath: `/${asset.dir}/${stem}.${hash}.${ext}`,
  };
});

const body = resolved
  .map(
    (asset) => `
/** Content hash of the ${asset.description} (first 8 hex of its sha256). */
export const ${asset.constant}_HASH = '${asset.hash}';

/** Cache-busting path for the ${asset.description}, relative to the site root. */
export const ${asset.constant}_PATH = '${asset.urlPath}';
`,
  )
  .join('');

const manifest = `// GENERATED by scripts/integration-assets-manifest.js — do not edit by hand.
//
// Re-run \`make integration-assets\` after editing any chart-platform study
// source, and commit the result. The hash is what makes a new build actually
// reach people instead of being answered from a Cloudflare edge still holding
// the previous bytes — see the header comment in that script.
${body}`;

if (checkOnly) {
  const manifestFile = path.join(ROOT, 'frontend/core/integrationAssets.ts');
  const current = fs.existsSync(manifestFile) ? fs.readFileSync(manifestFile, 'utf8') : '';
  if (current !== manifest) {
    console.error('  ✗ integrationAssets.ts is stale — run `make integration-assets`');
    process.exit(1);
  }
  console.log('  ✓ integrationAssets.ts is up to date');
  process.exit(0);
}

fs.writeFileSync(path.join(ROOT, 'frontend/core/integrationAssets.ts'), manifest);

for (const asset of resolved) {
  const publicDir = path.join(ROOT, 'frontend/public', asset.dir);
  fs.mkdirSync(publicDir, { recursive: true });

  // Take down hashed copies of THIS asset from earlier builds. public/ is
  // gitignored and never pruned by `git pull`, so without this the box
  // accumulates every version ever deployed — each still serving happily from
  // its own URL long after we stopped vouching for it.
  // Matched by hand rather than with a built regex: the stems contain dots,
  // so a pattern assembled from them needs escaping, and an escaping bug here
  // deletes published files rather than failing loudly.
  const { stem, ext } = splitExtension(asset.file);
  const prefix = `${stem}.`;
  const suffix = `.${ext}`;
  const isHashedCopy = (name) =>
    name.startsWith(prefix) &&
    name.endsWith(suffix) &&
    /^[0-9a-f]{8}$/.test(name.slice(prefix.length, name.length - suffix.length));

  for (const name of fs.readdirSync(publicDir)) {
    if (name !== asset.hashedName && isHashedCopy(name)) {
      fs.rmSync(path.join(publicDir, name), { force: true });
      console.log(`  · removed stale ${asset.dir}/${name}`);
    }
  }

  fs.copyFileSync(asset.source, path.join(publicDir, asset.hashedName));
  console.log(`  ✓ ${asset.constant.toLowerCase().replace('_study', '')} ${asset.urlPath}`);
}
