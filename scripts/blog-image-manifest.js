#!/usr/bin/env node
/**
 * blog-image-manifest.js - record the pixel size of every article image.
 *
 * Article images live in assets/blog/*.png and are copied to
 * frontend/public/blog by `make blog-images`, where markdown links like
 * `![alt](/blog/<name>.png)` pick them up. The component that renders them
 * (frontend/components/ExpandableImage.tsx) used to emit a plain <img> with no
 * width or height, so the browser had nothing to reserve space with until the
 * bytes arrived and the text below each screenshot jumped as it loaded. That
 * layout shift is scored against every article page, and it also kept the
 * images off next/image, which needs the intrinsic size up front to serve a
 * resized, re-encoded copy instead of the full PNG.
 *
 * Reading the dimensions at render time is not an option: the component is a
 * client component and the PNGs are not imported through the bundler (they
 * are copied in at deploy time, and the public/ copy is gitignored). So the
 * sizes are read here, once, straight from each PNG's IHDR chunk, and written
 * to a committed TypeScript module the component can import.
 *
 * Writes:
 *   frontend/core/blogImageManifest.ts   (committed - derived from the tracked
 *                                         assets, so a plain `npm run build`
 *                                         needs no pre-step)
 *
 * Dependency-free on purpose: `make blog-images` runs it on the deploy box,
 * the same constraint scripts/og-image-manifest.js works under.
 *
 * Usage: node scripts/blog-image-manifest.js [--check]
 *
 *   --check  don't write anything; exit non-zero if the committed manifest is
 *            out of date with respect to assets/blog/*.png
 */

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..');
const SOURCE_DIR = path.join(REPO_ROOT, 'assets/blog');
const MANIFEST = path.join(REPO_ROOT, 'frontend/core/blogImageManifest.ts');

const PNG_SIGNATURE = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

/**
 * Read width/height straight out of the IHDR chunk. It is required by the spec
 * to be the first chunk, so the offsets are fixed: 8-byte signature, 4-byte
 * length, 4-byte "IHDR" type, then the two big-endian uint32 dimensions.
 */
function readPngSize(file, buf) {
  if (buf.length < 24 || !buf.subarray(0, 8).equals(PNG_SIGNATURE)) {
    throw new Error(`${path.relative(REPO_ROOT, file)} is not a PNG`);
  }
  if (buf.subarray(12, 16).toString('ascii') !== 'IHDR') {
    throw new Error(`${path.relative(REPO_ROOT, file)} does not start with an IHDR chunk`);
  }
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

function scan() {
  if (!fs.existsSync(SOURCE_DIR)) return [];
  return fs
    .readdirSync(SOURCE_DIR)
    .filter((name) => name.endsWith('.png'))
    .sort()
    .map((name) => {
      const file = path.join(SOURCE_DIR, name);
      const { width, height } = readPngSize(file, fs.readFileSync(file));
      return { key: `/blog/${name}`, width, height };
    });
}

function render(entries) {
  const rows = entries
    .map(({ key, width, height }) => `  '${key}': { width: ${width}, height: ${height} },`)
    .join('\n');
  return `// GENERATED by scripts/blog-image-manifest.js - do not edit by hand.
//
// Re-run \`make blog-images\` (or \`node scripts/blog-image-manifest.js\`) after
// adding or replacing a PNG in assets/blog/, and commit the result. These are
// the intrinsic sizes next/image needs to reserve each article image's space
// before it loads and to serve a resized copy; see the header comment in that
// script for why they are read at build time rather than at render time.

/** Pixel dimensions of every assets/blog PNG, keyed by its public URL path. */
export const BLOG_IMAGE_DIMENSIONS: Record<string, { width: number; height: number }> = {
${rows}
};
`;
}

function main() {
  const check = process.argv.includes('--check');
  const entries = scan();
  const contents = render(entries);

  if (check) {
    const current = fs.existsSync(MANIFEST) ? fs.readFileSync(MANIFEST, 'utf8') : '';
    if (current !== contents) {
      console.error(
        'blog-image-manifest: frontend/core/blogImageManifest.ts is stale.\n' +
          '  Run `node scripts/blog-image-manifest.js` and commit the result.'
      );
      process.exit(1);
    }
    console.log(`blog-image-manifest: up to date (${entries.length} images)`);
    return;
  }

  fs.mkdirSync(path.dirname(MANIFEST), { recursive: true });
  fs.writeFileSync(MANIFEST, contents);
  console.log(`  ✓ blogImageManifest.ts (${entries.length} images)`);
}

try {
  main();
} catch (err) {
  console.error(`blog-image-manifest: ${err.message}`);
  process.exit(1);
}
